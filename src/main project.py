def clean_weather_value(x):
    if pd.isnull(x): return np.nan  # Keep NaNs
    x = str(x).strip()              # Convert to string, strip spaces
    if x in ['-', '—', '']:         # Handle missing values
        return np.nan
    # Use regex to find signed number with optional decimal
    match = re.search(r'-?\d+(\.\d+)?', x)
    return float(match.group()) if match else np.nan

