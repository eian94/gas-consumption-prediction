def forecast(model, last_sequence, steps, scaler_y, static_features):
    preds = []
    input_seq = last_sequence.copy()  # shape: (12, 4)

    for _ in range(steps):
        pred = model.predict(input_seq.reshape(1, *input_seq.shape), verbose=0)  # (1, 2)
        preds.append(pred[0])  # full 2-output

        next_input = static_features[-1]  # فرض: ویژگی‌ها تکراری
        input_seq = np.append(input_seq[1:], [next_input], axis=0)

    preds = np.array(preds)  # shape: (steps, 2)
    preds = scaler_y.inverse_transform(preds)
    return preds

